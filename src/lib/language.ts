const dictionary: Record<Language, Record<string, string>> = {
    en: {
        ...Object.fromEntries(Object.entries(frenchTranslations).map(([english, french]) => [french, english])),
        ...englishTranslations,
    },
    fr: frenchTranslations,
};

export function languageForSection(section: SchoolSection): Language {
    void section;
    return "en";
}

export function translateText(value: string, language: Language): string {
    const translations = dictionary[language];
    const exact = translations[value.trim()];
    if (exact) return value.replace(value.trim(), exact);

    const keys = Object.keys(translations).sort((a, b) => b.length - a.length);
    return keys.reduce((text, key) => {
        if (key.length < 4) return text;
        return text.replace(new RegExp(`(^|\\b)${escapeRegExp(key)}(?=\\b|$)`, "gi"), (match, prefix: string) => `${prefix}${translations[key]}`);
    }, value);
}

export function translateTextForCurrentSection(value: string): string {
    return translateText(value, languageForSection(getStoredSchoolSection()));
}

function escapeRegExp(value: string) {
    return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

type LanguageContextValue = {
    section: SchoolSection;
    language: Language;
    isFrench: boolean;
    t: (value: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [section, setSection] = useState<SchoolSection>(getStoredSchoolSection);
    const language = languageForSection(section);

    useEffect(() => {
        const refreshSection = () => setSection(getStoredSchoolSection());
        window.addEventListener("school-section-change", refreshSection);
        window.addEventListener("storage", refreshSection);
        return () => {
            window.removeEventListener("school-section-change", refreshSection);
            window.removeEventListener("storage", refreshSection);
        };
    }, []);

    useEffect(() => {
        document.documentElement.lang = language;
    }, [language]);

    const value = useMemo<LanguageContextValue>(() => ({
        section,
        language,
        isFrench: language === "fr",
        t: (text) => translateText(text, language),
    }), [section, language]);

    return createElement(LanguageContext.Provider, { value }, children);
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) throw new Error("useLanguage must be used within LanguageProvider");
    return context;
}
